"""Generate the icon theme: convert app icons, write index.theme, refresh the icon cache.

Incremental: a manifest records, per icon name, the source file (path, mtime, size)
and a hash of the settings. Unchanged icons are skipped, icons of removed apps are
deleted (only files the manifest owns), and a lock prevents concurrent runs.
"""
import fcntl
import hashlib
import io
import json
import os
import shutil
import subprocess

from . import config as C
from . import poster
from .iconfile import render
from .lookup import SAFE_NAME, IconResolver, Theme, installed_apps

MARKER = ".monotile"          # identifies a theme folder we created
OVERRIDE_EXTS = (".svg", ".png")


def default_source(name):
    for t in ("Papirus", "Papirus-Dark"):
        if t != name and Theme(t).exists:
            return t
    return "hicolor"


def settings_hash(cfg):
    key = {"algo": poster.ALGO_VERSION, "shape": cfg["shape"], "tones": cfg["tones"], "sizes": cfg["sizes"]}
    return hashlib.sha256(json.dumps(key, sort_keys=True).encode()).hexdigest()[:16]


def find_overrides():
    """{icon name: path} for user-made icons in the overrides folder."""
    out, d = {}, C.overrides_dir()
    if os.path.isdir(d):
        for f in sorted(os.listdir(d)):
            base, ext = os.path.splitext(f)
            if ext.lower() in OVERRIDE_EXTS and SAFE_NAME.match(base) and ".." not in base:
                out[base] = os.path.join(d, f)
    return out


def plan(cfg):
    """Work out which icon names to produce and where each comes from."""
    source = cfg["source"] or default_source(cfg["name"])
    resolver = IconResolver(source, skip=(cfg["name"],))
    overrides = find_overrides()
    jobs, skipped = {}, []
    for app in installed_apps():
        name = app.icon_name
        if name is None:
            skipped.append((app.desktop_id, "icon is a file path" if app.icon_is_path else "unsafe icon name"))
            continue
        if name in jobs:
            continue
        if name in overrides:
            jobs[name] = ("override", overrides[name])
            continue
        path = resolver.resolve(name)
        if path:
            jobs[name] = ("convert", path)
        else:
            skipped.append((app.desktop_id, "icon not found"))
    for name, path in overrides.items():          # overrides for icons no app uses yet
        jobs.setdefault(name, ("override", path))
    return source, jobs, skipped


def _key(kind, path, shash):
    st = os.stat(path)
    return {"kind": kind, "src": os.path.realpath(path), "mtime": st.st_mtime_ns, "size": st.st_size, "settings": shash}


def _outputs(tdir, name, sizes):
    return [os.path.join(tdir, f"{s}x{s}", "apps", name + ".png") for s in sizes]


def _write_png(path, im):
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=False)
    C.atomic_write(path, buf.getvalue(), mode="wb")


def write_index(cfg, tdir, fallback):
    dirs = [f"{s}x{s}/apps" for s in cfg["sizes"]]
    lines = ["[Icon Theme]", f"Name={cfg['name']}",
             "Comment=Monochrome app icons generated by monotile",
             f"Inherits={fallback},hicolor" if fallback != "hicolor" else "Inherits=hicolor",
             "Directories=" + ",".join(dirs), ""]
    for s, d in zip(cfg["sizes"], dirs):
        lines += [f"[{d}]", f"Size={s}", "Context=Applications", "Type=Fixed", ""]
    C.atomic_write(os.path.join(tdir, "index.theme"), "\n".join(lines))


def update_icon_cache(tdir):
    exe = shutil.which("gtk-update-icon-cache") or shutil.which("gtk4-update-icon-cache")
    if exe:
        subprocess.run([exe, "-f", "-t", "-q", tdir], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def generate(cfg, fallback, dry_run=False, log=print):
    """Bring the theme up to date. Returns a stats dict."""
    tdir = C.theme_dir(cfg)
    if os.path.isdir(tdir) and not os.path.exists(os.path.join(tdir, MARKER)) and os.listdir(tdir):
        raise RuntimeError(f"{tdir} exists and was not created by monotile; pick another name")
    os.makedirs(C.cache_dir(), exist_ok=True)
    lock = open(os.path.join(C.cache_dir(), "lock"), "w")
    fcntl.flock(lock, fcntl.LOCK_EX)
    try:
        return _generate(cfg, fallback, tdir, dry_run, log)
    finally:
        fcntl.flock(lock, fcntl.LOCK_UN)
        lock.close()


def _generate(cfg, fallback, tdir, dry_run, log):
    mpath = os.path.join(C.cache_dir(), "manifest-%s.json" % cfg["name"])
    try:
        with open(mpath, encoding="utf-8") as f:
            manifest = json.load(f)
    except (OSError, ValueError):
        manifest = {}
    source, jobs, skipped = plan(cfg)
    shash = settings_hash(cfg)
    stats = {"source": source, "fallback": fallback, "converted": 0, "overrides": 0,
             "unchanged": 0, "removed": 0, "failed": [], "skipped": skipped}

    for name in sorted(set(manifest) - set(jobs)):            # apps that went away
        stats["removed"] += 1
        if not dry_run:
            for p in _outputs(tdir, name, manifest[name].get("sizes", cfg["sizes"])):
                if os.path.exists(p):
                    os.unlink(p)
            del manifest[name]

    changed = stats["removed"] > 0
    for name, (kind, path) in sorted(jobs.items()):
        try:
            key = _key(kind, path, shash)
        except OSError as e:
            stats["failed"].append((name, str(e)))
            continue
        outs = _outputs(tdir, name, cfg["sizes"])
        old = manifest.get(name, {})
        if {k: old.get(k) for k in key} == key and all(os.path.exists(p) for p in outs):
            stats["unchanged"] += 1
            continue
        if dry_run:
            stats["overrides" if kind == "override" else "converted"] += 1
            continue
        try:
            if kind == "override":
                images = {s: render(path, s) for s in cfg["sizes"]}
            else:
                images, _ = poster.convert(path, cfg["sizes"], cfg["shape"], cfg["tones"])
            for s, p in zip(cfg["sizes"], outs):
                _write_png(p, images[s])
            for p in set(_outputs(tdir, name, old.get("sizes", []))) - set(outs):   # sizes no longer wanted
                if os.path.exists(p):
                    os.unlink(p)
        except Exception as e:                              # one bad icon never stops the run
            stats["failed"].append((name, f"{type(e).__name__}: {e}"))
            continue
        manifest[name] = dict(key, sizes=cfg["sizes"])
        stats["overrides" if kind == "override" else "converted"] += 1
        changed = True

    if not dry_run:
        os.makedirs(tdir, exist_ok=True)
        open(os.path.join(tdir, MARKER), "a").close()
        write_index(cfg, tdir, fallback)
        C.atomic_write(mpath, json.dumps(manifest, indent=1, sort_keys=True))
        if changed or not os.path.exists(os.path.join(tdir, "icon-theme.cache")):
            update_icon_cache(tdir)
    stats["changed"] = changed
    return stats


def remove(cfg):
    """Delete the generated theme folder (only if monotile created it) and its manifest."""
    tdir = C.theme_dir(cfg)
    if os.path.isdir(tdir) and os.path.exists(os.path.join(tdir, MARKER)):
        shutil.rmtree(tdir)
    mpath = os.path.join(C.cache_dir(), "manifest-%s.json" % cfg["name"])
    if os.path.exists(mpath):
        os.unlink(mpath)
